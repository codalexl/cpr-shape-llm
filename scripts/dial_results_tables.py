#!/usr/bin/env python3
"""Tables for the dial results chapter, from the executed records (analysis/SPINE.md sections 4 and 6).

    python scripts/dial_results_tables.py [--root checkpoints/dial] [--out thesis/tables/dial]

Writes one LaTeX booktabs table per readout where the thesis inputs them, plus summary.json under results/dial. Every number is composed from the
estimators in scripts/evaluate_dial.py (summarise, channel, policy_class), which tests/test_evaluate_dial.py
pins; nothing is computed twice in two places.

  coplay.tex      per arm and seed: survival, restraint, return per episode, living-round rate
  classes.tex     per arm and seed: the four probe rates, their round counts, and the policy class
  currency.tex    per arm: joint-action shares on living rounds, and survival
  frozen.tex      per evaluated shaper: E1 and E2 class counts, and E3 against E4 per-round return
  channel.tex     per arm and seed: the within-trial channel on the training records
  value_loss.tex  agent 2, slow and ShapeLLM-style: value loss at the start and the end
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import evaluate_dial as ed  # noqa: E402
from dial_records import tape_dir  # noqa: E402

M2 = ["m2_naive", "m2_slow", "m2_tbn_matched", "m2_shaper_matched", "m2_tbn_slow", "m2_shaper_slow",
      "m2_shapellm", "m2_shaper_matched_split", "m2_shapellm_history_off"]
M3 = ["m3_naive", "m3_slow", "m3_shapellm"]
SHAPERS = ["shapellm", "shaper_matched", "shaper_matched_split"]
LABEL = {"m2_naive": "naive", "m2_slow": "slow", "m2_tbn_matched": "tbn-matched",
         "m2_shaper_matched": "shaper-matched", "m2_tbn_slow": "tbn-slow", "m2_shaper_slow": "shaper-slow",
         "m2_shapellm": "ShapeLLM-style", "m2_shaper_matched_split": "split credit",
         "m2_shapellm_history_off": "history off", "m3_naive": "naive", "m3_slow": "slow",
         "m3_shapellm": "ShapeLLM-style", "shapellm": "ShapeLLM-style", "shaper_matched": "shaper-matched",
         "shaper_matched_split": "split credit"}
CELLS = ("11", "12", "21", "22")


def regime(arm):
    return "2" if arm.startswith("m2_") else "3"


def fmt(x, digits=2):
    return "---" if x is None else f"{x:.{digits}f}"


def latex(caption, label, columns, header, rows, size=r"\small", colsep=None, spacing=None, fit=False, short=None):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    sep = f"\\setlength{{\\tabcolsep}}{{{colsep}}}%\n" if colsep else ""
    space = f"{spacing}\n" if spacing else ""
    tabular = (f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n" + " & ".join(header) + r" \\" +
               f"\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n")
    if fit:
        tabular = f"\\resizebox{{\\textwidth}}{{!}}{{%\n{tabular}}}\n"
    cap = f"\\caption[{short}]{{{caption}}}" if short else f"\\caption{{{caption}}}"
    return (f"% generated by scripts/dial_results_tables.py\n"
            f"\\begin{{table}}[ht]\n\\centering\n{size}\n{space}{sep}{cap}\n\\label{{{label}}}\n"
            f"{tabular}\\end{{table}}\n")


def window(root, arm, w):
    return [(seed, ed.summarise(rec, window=w)) for seed, rec in ed.runs(tape_dir(arm, root))]


def coplay(root, arms, w):
    returns, rates, data = [], [], {}
    for arm in arms:
        for seed, rec in ed.runs(tape_dir(arm, root)):
            s = ed.summarise(rec, window=w)
            if not s:
                continue
            live = ed.live_per_round(rec, window=w)
            data.setdefault(arm, {})[seed] = {**s, "live_per_round": live}
            ident = [regime(arm), LABEL[arm], str(seed)]
            returns.append(ident + [fmt(s["survival"]),
                                    fmt(s["return_per_episode"][0], 1), fmt(s["return_per_episode"][1], 1)])
            rates.append(ident + [fmt(s["restraint_1"]), fmt(s["restraint_2"]),
                                  fmt(live[0] if live else None), fmt(live[1] if live else None)])
    # Two tables at \\small, with no \\resizebox. Ten columns on the text width were below 12 pt.
    episode = latex("Co-play over epochs 81--100, one row per seed. "
                    "Agent~1 is the naive learner in every arm. "
                    "Return/ep sums every logged round, and rounds after the pool dies contribute zero.",
                    "tab:coplay", "cllrrr",
                    ["$m$", "Arm", "Seed", "Survival", "Return/ep A1", "Return/ep A2"], returns,
                    size=r"\small\renewcommand{\arraystretch}{0.94}", colsep="5pt", spacing=r"\singlespacing",
                    short="Co-play returns, epochs 81--100")
    living = latex("Restraint and living-round receipts over epochs 81--100, the same seeds as "
                   "Table~\\ref{tab:coplay}. "
                   "Restraint is the share of living rounds on which that agent takes~1. "
                   "Live is receipts on living rounds divided by the number of living rounds.",
                   "tab:coplay-live", "cllrrrr",
                   ["$m$", "Arm", "Seed", "Restraint A1", "Restraint A2", "Live A1", "Live A2"], rates,
                   size=r"\small\renewcommand{\arraystretch}{0.94}", colsep="4pt", spacing=r"\singlespacing",
                   short="Restraint and living-round rates")
    return episode + "\n" + living, data


def classes(root, arms, w):
    rows, data = [], {}
    for arm in arms:
        for seed, rec in ed.runs(tape_dir(f"{arm[:2]}_probe_of_{arm}", root)):
            s = ed.summarise(rec, window=w)
            if not s:
                continue
            r = s["agent1_rates"]
            data.setdefault(arm, {})[seed] = {"class": s["agent1_class"],
                                              **{k: r[k]["rate"] for k in r}, "rounds": {k: r[k]["rounds"] for k in r}}
            rows.append([regime(arm), LABEL[arm], str(seed)] + [fmt(r[k]["rate"]) for k in
                        ("after_restrain", "after_take", "low", "high")] +
                        [str(min(r[k]["rounds"] for k in r)), s["agent1_class"]])
    table = latex("Probe of the frozen agent~1, per arm and seed. Rates are the probability of taking~1; "
                  "the count column is the smallest cell the class rests on.",
                  "tab:classes", "cllrrrrrl",
                  ["$m$", "Arm", "Seed", r"$r_{\text{after restrain}}$", r"$r_{\text{after take}}$",
                   r"$r_{\text{low}}$", r"$r_{\text{high}}$", "Min.\\ cell", "Class"], rows,
                  size=r"\footnotesize", colsep="3pt", spacing=r"\singlespacing",
                  short="Probe of the frozen agent 1")
    return table, data


def currency(root, arms, w):
    rows, data = [], {}
    for arm in arms:
        cells, keep = Counter(), []
        for seed, rec in ed.runs(tape_dir(arm, root)):
            s = ed.summarise(rec, window=w)
            if not s:
                continue
            keep.append(s)
            n_epochs = max(int(e) for e in rec["epoch"]) + 1
            for i in range(len(rec["epoch"])):
                if not rec["masked"][i] and int(rec["epoch"][i]) >= n_epochs - w:
                    cells[f"{int(rec['request_1'][i])}{int(rec['request_2'][i])}"] += 1
        if not keep:
            continue
        n = sum(cells.values()) or 1
        mean = lambda f: sum(f(s) for s in keep) / len(keep)  # noqa: E731
        data[arm] = {"seeds": len(keep), "reward_per_step": [mean(lambda s: s["return_per_round"][0]),
                                                             mean(lambda s: s["return_per_round"][1])],
                     "cells": {c: cells[c] / n for c in CELLS}, "survival": mean(lambda s: s["survival"])}
        rows.append([regime(arm), LABEL[arm], str(len(keep))] +
                    [fmt(cells[c] / n) for c in CELLS] + [fmt(data[arm]["survival"])])
    table = latex("Joint-action shares on living rounds, and survival, over epochs 81--100. "
                  "The shares pool every living round across seeds. Survival is the unweighted mean of the seeds. "
                  "Cell~11 is both take~1. Cell~12 is the naive learner taking~1 while agent~2 takes~2. "
                  "Cell~21 is the reverse. Cell~22 is both take~2. "
                  "Episode returns are in Table~\\ref{tab:coplay}. "
                  "Living-round rates are in Table~\\ref{tab:coplay-live}. "
                  "A rate that divides receipts by every logged round, including rounds after the pool has died, is not a column.",
                  "tab:currency", "cllrrrrr",
                  ["$m$", "Arm", "Seeds", "11", "12", "21", "22", "Survival"], rows,
                  short="Joint actions and survival")
    return table, data


def frozen(root, stage, w):
    rows, data = [], {}
    for arm in (SHAPERS if stage == "m2" else ["shapellm"]):
        entry = {}
        for kind in ("e1_transfer", "e2_replay"):
            counts = Counter()
            for seed, rec in ed.runs(tape_dir(f"{stage}_probe_of_{stage}_{kind}_{arm}", root)):
                s = ed.summarise(rec, window=w)
                if s:
                    counts[s["agent1_class"]] += 1
            entry[kind] = dict(counts)
        e3 = {s: v for s, v in window(root, f"{stage}_e3_frozen_partner_{arm}", w)}
        e4 = {s: v for s, v in window(root, f"{stage}_e4_untrained_partner_{arm}", w)}
        pairs = [(e3[k]["return_per_round"][1], e4[k]["return_per_round"][1]) for k in sorted(e3)
                 if k in e4 and e3[k] and e4[k]]
        entry["e3_vs_e4"] = {"wins": sum(a > b for a, b in pairs), "n": len(pairs),
                             "e3": [a for a, _ in pairs], "e4": [b for _, b in pairs]}
        data[arm] = entry
        show = lambda c: ", ".join(f"{k} {v}" for k, v in sorted(c.items())) or "---"  # noqa: E731
        rows.append([LABEL[arm], show(entry["e1_transfer"]), show(entry["e2_replay"]),
                     f"{entry['e3_vs_e4']['wins']}/{entry['e3_vs_e4']['n']}",
                     fmt(sum(entry["e3_vs_e4"]["e3"]) / max(len(pairs), 1)),
                     fmt(sum(entry["e3_vs_e4"]["e4"]) / max(len(pairs), 1))])
    table = latex("Frozen battery. E1 and E2 columns are probe classes of the fresh naive learner. "
                  "E3 and E4 are agent~2's per-round return against the naive learner it trained with and against an untrained one.",
                  "tab:frozen", "lllrrr",
                  ["Shaper", "E1 classes", "E2 classes", r"E3 $>$ E4", "E3 return", "E4 return"], rows,
                  size=r"\footnotesize", spacing=r"\singlespacing", fit=True,
                  short="Frozen battery")
    return table, data


def channel(root, arms):
    rows, data = [], {}
    for arm in arms:
        for seed, rec in ed.runs(tape_dir(arm, root)):
            c = ed.channel(rec)
            if not c or c["r"] is None:
                continue
            data.setdefault(arm, {})[seed] = c
            rows.append([regime(arm), LABEL[arm], str(seed), f"{c['r']:+.3f}", f"[{c['low']:+.3f}, {c['high']:+.3f}]",
                         fmt(c["partial"], 3), str(c["pairs"]), c["reading"]])
    table = latex("Within-trial channel on the training records: agent~2's restraint share in an episode "
                  "against agent~1's change in restraint share into the next episode.",
                  "tab:channel", "cllrlrrl",
                  ["$m$", "Arm", "Seed", "$r$", "95\\% interval", "Partial $r$", "Pairs", "Reading"], rows,
                  short="Within-trial channel")
    return table, data


def value_loss(root, w):
    """Agent 2's logged value loss, mean of the first three updates and of the last three.

    The training log stores the unweighted value loss, not that loss times the value coefficient.
    A single update jumps, so the paragraph's opening and finish are three-update means.
    """
    rows = []
    # Round tapes of the chained arms are in the uncut archive. Their training
    # logs are not. The logs under those names in checkpoints/dial are the hybrid.
    for arm in ("m2_slow",):
        for seed, rec in ed.runs(tape_dir(arm, root)):
            path = tape_dir(arm, root) / f"exp{seed + 1}_model2_training_metrics.txt"
            if not path.exists():
                continue
            values = json.loads(path.read_text())["value_loss"]
            if len(values) < 3:
                continue
            s = ed.summarise(rec, window=w)
            if not s:
                continue
            first, last = sum(values[:3]) / 3, sum(values[-3:]) / 3
            rows.append([LABEL[arm], str(seed), str(len(values)), f"{first:.1f}", f"{last:.1f}", fmt(s["survival"])])
    table = latex("Agent~2's logged value loss, the mean of the first three updates and of the last three. "
                  "The loss is the unweighted value loss in the training log, not that loss times the value coefficient. "
                  "Survival is the share of episodes still alive at round~50 over epochs 81--100. "
                  "The arm is the naive learner on the slow step. "
                  "The uncut archive does not contain the chained training logs, and the logs "
                  "under those names in the checkpoint folder are the later hybrid, so they are not in this table.",
                  "tab:value-loss", "llrrrr",
                  ["Arm", "Seed", "Updates", "First three", "Last three", "Survival"], rows,
                  short="Logged value loss")
    return table, rows


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default="checkpoints/dial")
    ap.add_argument("--out", default="thesis/tables/dial")
    ap.add_argument("--window", type=int, default=20)
    a = ap.parse_args(argv)
    root, out = ROOT / a.root, ROOT / a.out
    out.mkdir(parents=True, exist_ok=True)
    arms = M2 + M3
    tables, summary = {}, {}
    tables["coplay"], summary["coplay"] = coplay(root, arms, a.window)
    tables["classes"], summary["classes"] = classes(root, arms, a.window)
    tables["currency"], summary["currency"] = currency(root, arms, a.window)
    tables["frozen"], summary["frozen"] = frozen(root, "m2", a.window)
    tables["channel"], summary["channel"] = channel(root, M2[:1] + ["m2_tbn_matched", "m2_shaper_matched",
                                                                   "m2_shaper_matched_split", "m2_shapellm"])
    tables["value_loss"], summary["value_loss"] = value_loss(root, a.window)
    for name, text in tables.items():
        (out / f"{name}.tex").write_text(text)
    data = ROOT / "results" / "dial" / "tables_summary.json"
    data.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    for name in tables:
        print(f"wrote {(out / (name + '.tex')).relative_to(ROOT)}")
    print(f"wrote {data.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
